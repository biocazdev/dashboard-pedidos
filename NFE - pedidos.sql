SELECT DISTINCT

    C5.C5_FILIAL       AS FILIAL,
    C5.C5_NUM          AS PEDIDO,
    C5.C5_EMISSAO      AS DATA_PEDIDO,
    C5.C5_CLIENTE      AS CLIENTE,
    C5.C5_LOJACLI      AS LOJA,
    C5.C5_VEND1        AS VENDEDOR,

    -- CONDICAO DE PAGAMENTO
    C5.C5_CONDPAG      AS COD_COND_PAGTO,
    E4.E4_DESCRI       AS DESC_COND_PAGTO,

    -- NOTA FISCAL
    D2.D2_DOC          AS NOTA_FISCAL,
    D2.D2_SERIE        AS SERIE,
    F2.F2_EMISSAO      AS DATA_NOTA,
    F2.F2_CHVNFE       AS CHAVE_NFE,

    -- PARCELAS FINANCEIRAS
    E1.E1_PREFIXO      AS PREFIXO,
    E1.E1_PARCELA      AS PARCELA,
    E1.E1_TIPO         AS TIPO_TITULO,
    E1.E1_VENCTO       AS VENCIMENTO,
    E1.E1_VALOR        AS VALOR_PARCELA,
    E1.E1_SALDO        AS SALDO_PARCELA,

    CASE
        WHEN NULLIF(LTRIM(RTRIM(F2.F2_CHVNFE)), '') IS NOT NULL
            THEN 'COM NFE'

        WHEN D2.D2_DOC IS NOT NULL
            THEN 'COM NOTA SEM CHAVE NFE'

        ELSE 'SEM NOTA VINCULADA'
    END AS STATUS_NFE

FROM SC5010 C5

INNER JOIN SC6010 C6
    ON C6.C6_FILIAL = C5.C5_FILIAL
   AND C6.C6_NUM = C5.C5_NUM
   AND C6.D_E_L_E_T_ = ''

-- ITENS DA NOTA FISCAL
LEFT JOIN SD2010 D2
    ON D2.D2_FILIAL = C6.C6_FILIAL
   AND D2.D2_PEDIDO = C6.C6_NUM
   AND D2.D2_ITEMPV = C6.C6_ITEM
   AND D2.D_E_L_E_T_ = ''

-- CABECALHO DA NOTA FISCAL
LEFT JOIN SF2010 F2
    ON F2.F2_FILIAL = D2.D2_FILIAL
   AND F2.F2_DOC = D2.D2_DOC
   AND F2.F2_SERIE = D2.D2_SERIE
   AND F2.F2_CLIENTE = D2.D2_CLIENTE
   AND F2.F2_LOJA = D2.D2_LOJA
   AND F2.D_E_L_E_T_ = ''

-- CONDICAO DE PAGAMENTO
LEFT JOIN SE4010 E4
    ON E4.E4_FILIAL = C5.C5_FILIAL
   AND E4.E4_CODIGO = C5.C5_CONDPAG
   AND E4.D_E_L_E_T_ = ''

-- PARCELAS DO CONTAS A RECEBER
LEFT JOIN SE1010 E1
    ON E1.E1_FILIAL = F2.F2_FILIAL
   AND E1.E1_NUM = F2.F2_DOC
   AND E1.E1_PREFIXO = F2.F2_SERIE
   AND E1.E1_CLIENTE = F2.F2_CLIENTE
   AND E1.E1_LOJA = F2.F2_LOJA
   AND E1.E1_TIPO = 'NF'
   AND E1.D_E_L_E_T_ = ''

WHERE C5.D_E_L_E_T_ = ''

  AND C5.C5_EMISSAO BETWEEN '20260101' AND '20261231'

  AND EXISTS (
      SELECT 1
      FROM SD2010 DX
      WHERE DX.D2_FILIAL = C5.C5_FILIAL
        AND DX.D2_PEDIDO = C5.C5_NUM
        AND DX.D_E_L_E_T_ = ''
  )

ORDER BY
    C5.C5_NUM,
    D2.D2_DOC,
    E1.E1_PARCELA;